ALTER TABLE courses ADD COLUMN IF NOT EXISTS college TEXT NOT NULL DEFAULT '';
ALTER TABLE courses ADD COLUMN IF NOT EXISTS class_name TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS course_spaces (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL UNIQUE,
  conversation_id BIGINT NOT NULL UNIQUE,
  invite_code TEXT NOT NULL UNIQUE,
  created_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE IF NOT EXISTS course_join_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL,
  student_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  requested_at TEXT DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  reviewed_at TEXT DEFAULT '',
  reviewed_by BIGINT,
  review_note TEXT DEFAULT '',
  UNIQUE(course_id, student_id)
);

CREATE INDEX IF NOT EXISTS course_join_requests_course_status
  ON course_join_requests(course_id, status, id DESC);

DO $$
DECLARE
  item RECORD;
  conversation_id BIGINT;
  code TEXT;
  student RECORD;
BEGIN
  FOR item IN
    SELECT c.id, c.name, c.college, c.class_name, a.user_id AS teacher_id, u.name AS teacher_name
    FROM courses c
    JOIN course_teacher_assignments a ON a.course_id = c.id
    JOIN users u ON u.id = a.user_id
    WHERE NOT EXISTS (SELECT 1 FROM course_spaces s WHERE s.course_id = c.id)
  LOOP
    INSERT INTO conversations (title, type, owner_id)
    VALUES (LEFT(CONCAT_WS('-', NULLIF(item.name, ''), NULLIF(item.college, ''), NULLIF(item.class_name, ''), item.teacher_name), 120), 'group', item.teacher_id)
    RETURNING id INTO conversation_id;
    LOOP
      code := UPPER(SUBSTR(MD5(RANDOM()::TEXT || item.id::TEXT || CLOCK_TIMESTAMP()::TEXT), 1, 8));
      EXIT WHEN NOT EXISTS (SELECT 1 FROM course_spaces WHERE invite_code = code);
    END LOOP;
    INSERT INTO course_spaces (course_id, conversation_id, invite_code) VALUES (item.id, conversation_id, code);
    INSERT INTO conversation_members (conversation_id, user_id) VALUES (conversation_id, item.teacher_id) ON CONFLICT DO NOTHING;
    INSERT INTO group_agents (conversation_id, user_id) VALUES (conversation_id, item.teacher_id) ON CONFLICT DO NOTHING;
    FOR student IN SELECT id FROM users WHERE role = 'student' AND college = item.college AND class = item.class_name LOOP
      INSERT INTO course_student_memberships (course_id, student_id) VALUES (item.id, student.id) ON CONFLICT DO NOTHING;
      INSERT INTO conversation_members (conversation_id, user_id) VALUES (conversation_id, student.id) ON CONFLICT DO NOTHING;
    END LOOP;
  END LOOP;
END $$;
