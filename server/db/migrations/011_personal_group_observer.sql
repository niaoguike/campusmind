ALTER TABLE group_feedback_consents ADD COLUMN IF NOT EXISTS receive_hints BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE group_feedback_consents ADD COLUMN IF NOT EXISTS hint_daily_limit INTEGER NOT NULL DEFAULT 5;

CREATE TABLE IF NOT EXISTS group_observer_hints (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  anchor_message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  anchor_version INTEGER NOT NULL,
  source_message_ids TEXT NOT NULL DEFAULT '[]',
  kind TEXT NOT NULL,
  title TEXT NOT NULL,
  teaser TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'unread',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  CHECK (status IN ('unread','read','dismissed')),
  UNIQUE (conversation_id,recipient_id,anchor_message_id)
);
CREATE INDEX IF NOT EXISTS group_observer_hints_recipient ON group_observer_hints(conversation_id,recipient_id,id DESC);

CREATE TABLE IF NOT EXISTS group_observer_scans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  minute_bucket BIGINT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS group_observer_scans_budget ON group_observer_scans(conversation_id,recipient_id,created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS group_observer_scans_unique_minute ON group_observer_scans(conversation_id,recipient_id,minute_bucket);

CREATE TABLE IF NOT EXISTS group_observer_followups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hint_id BIGINT NOT NULL REFERENCES group_observer_hints(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  created_at TEXT NOT NULL
);
