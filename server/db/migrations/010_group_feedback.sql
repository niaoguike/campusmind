ALTER TABLE messages ADD COLUMN IF NOT EXISTS deleted_at TEXT;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS ai_context_allowed BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS version INTEGER NOT NULL DEFAULT 1;
CREATE INDEX IF NOT EXISTS messages_conversation_cursor ON messages(conversation_id,id DESC);

CREATE TABLE IF NOT EXISTS group_feedback_settings (
  conversation_id BIGINT PRIMARY KEY REFERENCES conversations(id) ON DELETE CASCADE,
  observer_enabled BOOLEAN NOT NULL DEFAULT false,
  trigger_mode TEXT NOT NULL DEFAULT 'explicit',
  analysis_mode TEXT NOT NULL DEFAULT 'grounded_mad',
  updated_at TEXT NOT NULL DEFAULT '',
  CHECK (trigger_mode IN ('explicit','suggest')),
  CHECK (analysis_mode IN ('single','single_review','free_debate','grounded_mad'))
);
CREATE TABLE IF NOT EXISTS group_feedback_consents (
  conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  allow_context BOOLEAN NOT NULL DEFAULT false,
  revoked_at TEXT,
  updated_at TEXT NOT NULL DEFAULT '',
  PRIMARY KEY(conversation_id,user_id)
);
CREATE TABLE IF NOT EXISTS group_feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  requester_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  anchor_message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  anchor_version INTEGER NOT NULL,
  trigger_type TEXT NOT NULL,
  trigger_reason TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'queued',
  mode TEXT NOT NULL,
  visibility TEXT NOT NULL DEFAULT 'private',
  context_message_ids TEXT NOT NULL DEFAULT '[]',
  source_json TEXT NOT NULL DEFAULT '[]',
  result_json TEXT NOT NULL DEFAULT '{}',
  error_code TEXT NOT NULL DEFAULT '',
  model_name TEXT NOT NULL DEFAULT '',
  call_count INTEGER NOT NULL DEFAULT 0,
  duration_ms BIGINT NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  CHECK (status IN ('queued','running','completed','failed','hidden')),
  CHECK (visibility IN ('private','group')),
  CHECK (mode IN ('single','single_review','free_debate','grounded_mad'))
);
CREATE INDEX IF NOT EXISTS group_feedback_anchor ON group_feedback(conversation_id,anchor_message_id,id DESC);
CREATE UNIQUE INDEX IF NOT EXISTS group_feedback_active_unique ON group_feedback(conversation_id,anchor_message_id,anchor_version,requester_id,mode) WHERE status IN ('queued','running','completed');
CREATE TABLE IF NOT EXISTS group_feedback_followups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feedback_id BIGINT NOT NULL REFERENCES group_feedback(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL,
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  created_at TEXT NOT NULL
);
